const burger = document.querySelector('.burger-menu');  
const navLinks = document.querySelectorAll('.nav li');  
const mediaQuery = window.matchMedia("(max-width: 768px)");

function toggleBurgerMenu() {  
  document.body.classList.toggle('noScroll');  
  document.querySelector('header').classList.toggle('active');  
}  

function addNavLinkEventListeners() {  
  navLinks.forEach(link => {  
    link.addEventListener('click', toggleBurgerMenu);  
  });  
}  

function removeNavLinkEventListeners() {  
  navLinks.forEach(link => {  
    link.removeEventListener('click', toggleBurgerMenu);  
  });  
}  


function handleMediaQueryChange(event) {  
  if (event.matches) {  
    addNavLinkEventListeners();  
  } else {  
    removeNavLinkEventListeners();  
    document.body.classList.remove('noScroll');  
    document.querySelector('header').classList.remove('active');  
  }  
}  
 
handleMediaQueryChange(mediaQuery);  
mediaQuery.addEventListener("change", handleMediaQueryChange);  
burger.addEventListener('click', toggleBurgerMenu);  

